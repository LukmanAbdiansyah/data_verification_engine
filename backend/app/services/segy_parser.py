def detect_encoding(header_bytes: bytes) -> str:
    """Detect if textual header is ASCII or EBCDIC."""
    ascii_printable = sum(1 for b in header_bytes if 32 <= b <= 126)
    ebcdic_decoded = bytes(EBCDIC_TO_ASCII_TABLE.get(b, 0x20) for b in header_bytes)
    ebcdic_printable = sum(1 for b in ebcdic_decoded if 32 <= b <= 126)
    if ascii_printable > ebcdic_printable:
        return 'ASCII'
    return 'EBCDIC'

def decode_textual_header(header_bytes: bytes, encoding: str) -> List[str]:
    """Decode 3200-byte textual header into 40 lines of 80 characters."""
    if encoding == 'EBCDIC':
        decoded = bytes(EBCDIC_TO_ASCII_TABLE.get(b, 0x20) for b in header_bytes)
        text = decoded.decode('ascii', errors='replace')
    else:
        text = header_bytes.decode('ascii', errors='replace')
    lines = [text[i*80:(i+1)*80].rstrip() for i in range(40)]
    return lines

def read_binary_header(file_path: str) -> Dict[str, Any]:
    """Read binary header from bytes 3200-3600."""
    with open(file_path, 'rb') as f:
        f.seek(3200)
        data = f.read(400)
    if len(data) < 400:
        return {'error': 'Binary header too short'}
    job_id = struct.unpack('>i', data[0:4])[0]
    line_number = struct.unpack('>i', data[4:8])[0]
    reel_number = struct.unpack('>i', data[8:12])[0]
    num_traces = struct.unpack('>h', data[12:14])[0]
    num_aux_traces = struct.unpack('>h', data[14:16])[0]
    sample_interval = struct.unpack('>h', data[16:18])[0]
    sample_interval_orig = struct.unpack('>h', data[18:20])[0]
    samples_per_trace = struct.unpack('>h', data[20:22])[0]
    samples_per_trace_orig = struct.unpack('>h', data[22:24])[0]
    data_sample_format_code = struct.unpack('>h', data[24:26])[0]
    return {
        'job_id': job_id,
        'line_number': line_number,
        'reel_number': reel_number,
        'sample_interval': sample_interval,
        'samples_per_trace': samples_per_trace,
        'data_sample_format_code': data_sample_format_code,
    }

def validate_segy(file_path: str) -> Dict[str, Any]:
    """Full SEG-Y validation. Returns SegyValidationResult-compatible dict."""
    result = {
        'valid_segy': False,
        'textual_header_present': False,
        'textual_header_encoding': 'UNKNOWN',
        'textual_header_lines': [],
        'binary_header': {},
        'validation_errors': []
    }
    try:
        file_size = os.path.getsize(file_path)
        if file_size < 3600:
            result['validation_errors'].append('File too small for SEG-Y (< 3600 bytes)')
            return result
        
        with open(file_path, 'rb') as f:
            header_bytes = f.read(3200)
        
        if len(header_bytes) == 3200:
            encoding = detect_encoding(header_bytes)
            result['textual_header_encoding'] = encoding
            lines = decode_textual_header(header_bytes, encoding)
            non_empty = [l for l in lines if l.strip()]
            result['textual_header_present'] = len(non_empty) > 0
            result['textual_header_lines'] = lines
        
        binary = read_binary_header(file_path)
        if 'error' in binary:
            result['validation_errors'].append(binary['error'])
            return result
        result['binary_header'] = binary
        
        si = binary.get('sample_interval', 0)
        spt = binary.get('samples_per_trace', 0)
        fmt = binary.get('data_sample_format_code', 0)
        
        if si < 100 or si > 16000:
            result['validation_errors'].append(f'Unusual sample interval: {si} microseconds')
        if spt < 1 or spt > 100000:
            result['validation_errors'].append(f'Unusual samples per trace: {spt}')
        if fmt not in (1, 2, 3, 4, 5, 6, 7, 8, 15, 16):
            result['validation_errors'].append(f'Unrecognized format code: {fmt}')
        
        if not result['validation_errors']:
            result['valid_segy'] = True
        elif all('Unusual' in e or 'Unrecognized' in e for e in result['validation_errors']):
            result['valid_segy'] = True
            
    except Exception as e:
        result['validation_errors'].append(f'Error reading file: {str(e)}')
    
    return result
